create table public.calls (
  id uuid primary key default gen_random_uuid(),
  interaction_id uuid not null unique references public.interactions(id) on delete cascade,
  phone_number text,
  direction text not null default 'Outbound' check (direction in ('Inbound', 'Outbound')),
  started_at timestamptz not null,
  ended_at timestamptz,
  answered boolean not null default true,
  outcome text,
  decision_status text,
  decision_timeframe text,
  decision_due_at timestamptz,
  recording_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ended_at is null or ended_at >= started_at)
);

create table public.emails (
  id uuid primary key default gen_random_uuid(),
  interaction_id uuid not null unique references public.interactions(id) on delete cascade,
  from_address text not null,
  to_addresses text[] not null,
  cc_addresses text[] not null default '{}',
  sent_at timestamptz not null,
  delivery_status text not null default 'Sent'
    check (delivery_status in ('Draft', 'Sent', 'Delivered', 'Opened', 'Replied', 'Bounced')),
  opened_at timestamptz,
  replied_at timestamptz,
  response_time_minutes integer generated always as (
    case
      when replied_at is null then null
      else greatest(0, floor(extract(epoch from (replied_at - sent_at)) / 60)::integer)
    end
  ) stored,
  body_excerpt text,
  attachments_count integer not null default 0 check (attachments_count >= 0),
  message_reference text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (cardinality(to_addresses) > 0),
  check (opened_at is null or opened_at >= sent_at),
  check (replied_at is null or replied_at >= sent_at)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  interaction_id uuid not null unique references public.interactions(id) on delete cascade,
  platform text not null,
  direction text not null default 'Outbound' check (direction in ('Inbound', 'Outbound')),
  correspondent text,
  sent_at timestamptz not null,
  delivered_at timestamptz,
  read_at timestamptz,
  replied_at timestamptz,
  response_time_minutes integer generated always as (
    case
      when replied_at is null then null
      else greatest(0, floor(extract(epoch from (replied_at - sent_at)) / 60)::integer)
    end
  ) stored,
  content_excerpt text not null,
  message_status text not null default 'Sent'
    check (message_status in ('Sent', 'Delivered', 'Read', 'Replied', 'Failed')),
  external_reference text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (delivered_at is null or delivered_at >= sent_at),
  check (read_at is null or read_at >= sent_at),
  check (replied_at is null or replied_at >= sent_at)
);

create table public.meetings (
  id uuid primary key default gen_random_uuid(),
  interaction_id uuid not null unique references public.interactions(id) on delete cascade,
  meeting_mode text not null default 'In person'
    check (meeting_mode in ('In person', 'Video', 'Phone')),
  scheduled_at timestamptz not null,
  started_at timestamptz,
  ended_at timestamptz,
  appointment_status text not null default 'Scheduled'
    check (appointment_status in ('Scheduled', 'Confirmed', 'Completed', 'Cancelled', 'No show')),
  location text,
  meeting_url text,
  attendees text[] not null default '{}',
  agenda text,
  meeting_minutes text,
  decisions text,
  decision_due_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ended_at is null or started_at is null or ended_at >= started_at)
);

