create or replace function public.set_project_owner_from_client()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  select client.created_by
  into new.employee_id
  from public.clients client
  where client.id = new.client_id;

  if new.employee_id is null then
    raise exception 'The selected client does not exist or is not accessible';
  end if;

  return new;
end;
$$;

