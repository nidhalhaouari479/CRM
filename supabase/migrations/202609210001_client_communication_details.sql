create or replace function public.assert_interaction_detail_type()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  interaction_type text;
begin
  select interaction.type::text
  into interaction_type
  from public.interactions interaction
  where interaction.id = new.interaction_id;

  if interaction_type is null then
    raise exception 'The interaction does not exist or is not accessible';
  end if;

  if not (interaction_type = any(tg_argv)) then
    raise exception 'Interaction type % is not valid for table %', interaction_type, tg_table_name;
  end if;

  return new;
end;
$$;

