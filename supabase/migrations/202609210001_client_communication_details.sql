-- One database call creates the common interaction and its channel details atomically.
create or replace function public.create_interaction_with_details(
  p_client_id uuid,
  p_type public.interaction_kind,
  p_subject text,
  p_date timestamptz,
  p_duration_minutes integer default null,
  p_summary text default '',
  p_client_request text default null,
  p_employee_response text default null,
  p_next_action text default null,
  p_next_contact_date timestamptz default null,
  p_details jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
set search_path = public
as $$
declare
  interaction_id uuid;
  employee_id uuid;
  address_list text[];
begin
  employee_id := public.current_profile_id();
  if employee_id is null then
    raise exception 'Authentication required';
  end if;

  insert into public.interactions (
    client_id, employee_id, type, subject, date, duration_minutes, summary,
    client_request, employee_response, next_action, next_contact_date
  ) values (
    p_client_id, employee_id, p_type, p_subject, p_date, p_duration_minutes, p_summary,
    p_client_request, p_employee_response, p_next_action, p_next_contact_date
  ) returning id into interaction_id;

  case p_type
    when 'Call' then
      insert into public.calls (
        interaction_id, phone_number, direction, started_at, ended_at, answered,
        outcome, decision_status, decision_timeframe, decision_due_at, recording_url
      ) values (
        interaction_id,
        nullif(p_details ->> 'phone_number', ''),
        coalesce(nullif(p_details ->> 'direction', ''), 'Outbound'),
        coalesce(nullif(p_details ->> 'started_at', '')::timestamptz, p_date),
        nullif(p_details ->> 'ended_at', '')::timestamptz,
        coalesce(nullif(p_details ->> 'answered', '')::boolean, true),
        nullif(p_details ->> 'outcome', ''),
        nullif(p_details ->> 'decision_status', ''),
        nullif(p_details ->> 'decision_timeframe', ''),
        nullif(p_details ->> 'decision_due_at', '')::timestamptz,
        nullif(p_details ->> 'recording_url', '')
      );
    when 'Email' then
      address_list := regexp_split_to_array(nullif(p_details ->> 'to_addresses', ''), '\s*,\s*');
      insert into public.emails (
        interaction_id, from_address, to_addresses, cc_addresses, sent_at,
        delivery_status, opened_at, replied_at, body_excerpt,
        attachments_count, message_reference
      ) values (
        interaction_id,
        p_details ->> 'from_address',
        address_list,
        coalesce(regexp_split_to_array(nullif(p_details ->> 'cc_addresses', ''), '\s*,\s*'), '{}'),
        coalesce(nullif(p_details ->> 'sent_at', '')::timestamptz, p_date),
        coalesce(nullif(p_details ->> 'delivery_status', ''), 'Sent'),
        nullif(p_details ->> 'opened_at', '')::timestamptz,
        nullif(p_details ->> 'replied_at', '')::timestamptz,
        nullif(p_details ->> 'body_excerpt', ''),
        coalesce(nullif(p_details ->> 'attachments_count', '')::integer, 0),
        nullif(p_details ->> 'message_reference', '')
      );
    when 'WhatsApp', 'Message' then
      insert into public.messages (
        interaction_id, platform, direction, correspondent, sent_at, delivered_at,
        read_at, replied_at, content_excerpt, message_status, external_reference
      ) values (
        interaction_id,
        coalesce(nullif(p_details ->> 'platform', ''), p_type::text),
        coalesce(nullif(p_details ->> 'direction', ''), 'Outbound'),
        nullif(p_details ->> 'correspondent', ''),
        coalesce(nullif(p_details ->> 'sent_at', '')::timestamptz, p_date),
        nullif(p_details ->> 'delivered_at', '')::timestamptz,
        nullif(p_details ->> 'read_at', '')::timestamptz,
        nullif(p_details ->> 'replied_at', '')::timestamptz,
        coalesce(nullif(p_details ->> 'content_excerpt', ''), p_summary),
        coalesce(nullif(p_details ->> 'message_status', ''), 'Sent'),
        nullif(p_details ->> 'external_reference', '')
      );
    when 'Meeting', 'Video Call' then
      insert into public.meetings (
        interaction_id, meeting_mode, scheduled_at, started_at, ended_at,
        appointment_status, location, meeting_url, attendees, agenda,
        meeting_minutes, decisions, decision_due_at
      ) values (
        interaction_id,
        coalesce(
          nullif(p_details ->> 'meeting_mode', ''),
          case when p_type = 'Video Call' then 'Video' else 'In person' end
        ),
        coalesce(nullif(p_details ->> 'scheduled_at', '')::timestamptz, p_date),
        nullif(p_details ->> 'started_at', '')::timestamptz,
        nullif(p_details ->> 'ended_at', '')::timestamptz,
        coalesce(nullif(p_details ->> 'appointment_status', ''), 'Scheduled'),
        nullif(p_details ->> 'location', ''),
        nullif(p_details ->> 'meeting_url', ''),
        coalesce(regexp_split_to_array(nullif(p_details ->> 'attendees', ''), '\s*,\s*'), '{}'),
        nullif(p_details ->> 'agenda', ''),
        nullif(p_details ->> 'meeting_minutes', ''),
        nullif(p_details ->> 'decisions', ''),
        nullif(p_details ->> 'decision_due_at', '')::timestamptz
      );
    else
      null;
  end case;

  return interaction_id;
end;
$$;

