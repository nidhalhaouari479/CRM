create or replace view public.client_financial_summary
with (security_invoker = true)
as
select
  client.id as client_id,
  count(project.id) as project_count,
  coalesce(sum(project.final_price), 0)::numeric(14,3) as project_amount,
  coalesce(sum(project.payment_amount), 0)::numeric(14,3) as paid_amount,
  coalesce(sum(project.remaining_amount), 0)::numeric(14,3) as unpaid_amount
from public.clients client
left join public.projects project on project.client_id = client.id
group by client.id;

