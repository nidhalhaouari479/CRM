export function frenchLabel(value: string): string {
  return labels[value] ?? value;
}

export function activityLabel(action: string): string {
  if (action === "project.status_changed") return "Statut du projet modifié";
  const [entity, operation] = action.split(".");
  const operations: Record<string, string> = {
    insert: "Création",
    update: "Modification",
    delete: "Suppression",
  };
  return operations[operation] && labels[entity]
    ? `${operations[operation]} · ${labels[entity]}`
    : "Activité enregistrée";
}
